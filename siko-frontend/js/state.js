// Subscriber system for reactive re-rendering
const listeners = [];

export function subscribe(callback) {
  listeners.push(callback);
}

export function notifyStateChange() {
  listeners.forEach(callback => callback(AppState));
}

export function setRole(newRole) {
  AppState.currentRole = newRole;
  if (newRole === 'guest') {
    AppState.currentView = 'public-home';
    AppState.isLoggedIn = false;
    AppState.currentUser = null;
  }
  else if (newRole === 'student') {
    AppState.currentView = 'student-home';
    AppState.currentUser = { id: 'usr-student-01', name: 'Enrolled Student', email: 'student@siko.demo', role: 'student', grade: 'Class 11', board: 'CBSE' };
    AppState.isLoggedIn = true;
  }
  else if (newRole === 'teacher') {
    const isActivated = AppState.teacherOnboarding && AppState.teacherOnboarding.portalActivatedAfterOrientation;
    AppState.currentView = isActivated ? 'teacher-dashboard' : 'teacher-onboarding';
    AppState.currentUser = {
      id: 'usr-teacher-01',
      name: (AppState.teacherOnboarding && AppState.teacherOnboarding.fullName) ? AppState.teacherOnboarding.fullName : 'Faculty Member',
      email: 'teacher@siko.demo',
      role: 'teacher',
      tier: 'Master',
      subject: 'Physics'
    };
    AppState.isLoggedIn = true;
  }
  else if (newRole === 'parent') {
    AppState.currentView = 'parent-dashboard';
    AppState.currentUser = { id: 'usr-parent-01', name: 'Parent / Legal Guardian', email: 'parent@siko.demo', role: 'parent', childName: 'Enrolled Student' };
    AppState.isLoggedIn = true;
  }
  else if (newRole === 'admin') {
    AppState.currentView = 'admin-dashboard';
    AppState.currentUser = { id: 'usr-admin-01', name: 'SIKO CFO & Executive Admin', email: 'admin@joinsiko.com', role: 'admin' };
    AppState.isLoggedIn = true;
  }
  notifyStateChange();
}

export function setView(viewName) {
  AppState.previousView = AppState.currentView;
  AppState.currentView = viewName;
  window.scrollTo({ top: 0, behavior: 'smooth' });
  notifyStateChange();
}

export function setCurrency(currencyCode) {
  if (currencies[currencyCode]) {
    AppState.selectedCurrency = currencyCode;
    notifyStateChange();
  }
}

export function setTimezone(timezoneCode) {
  if (timezones[timezoneCode]) {
    AppState.selectedTimezone = timezoneCode;
    notifyStateChange();
  }
}

export function formatPrice(inrAmount) {
  const curr = currencies[AppState.selectedCurrency];
  const converted = Math.round(inrAmount * curr.rate);
  return `${curr.symbol}${converted.toLocaleString()}`;
}

window.AppState = AppState;

